	[Fact]
	public void AnalysisFallbackKeepsLargeOrdinaryMatchAndSharedQuotas() {
		var options = Options( false, false );
		const string pattern = @"(*ANY)(?m)^(){499}\1B";
		var reference = Reference( pattern, options );
		AssertLiteral( reference, "B"u8.ToArray(), 0, "0:1,0:0" );
		Compare( reference, "B"u8.ToArray(), 0, Compile( pattern, options ).Match( "B"u8.ToArray() ), "ordinary fallback" );
		Assert.Equal( PcreByteDiagnosticCode.PatternRepeatLimitExceeded, PcreByteCompiler.Compile( "A{4096}"u8.ToArray(), options ).Diagnostic?.Code );
		var captures = Encoding.ASCII.GetBytes( String.Concat( Enumerable.Repeat( "()", 257 ) ) );
		Assert.Equal( PcreByteDiagnosticCode.PatternCaptureLimitExceeded, PcreByteCompiler.Compile( captures, options ).Diagnostic?.Code );
		var deep = String.Concat( new string( '(', 257 ), new string( ')', 257 ) );
		Assert.Equal( PcreByteDiagnosticCode.PatternDepthLimitExceeded, PcreByteCompiler.Compile( Encoding.ASCII.GetBytes( deep ), options ).Diagnostic?.Code );
	}

