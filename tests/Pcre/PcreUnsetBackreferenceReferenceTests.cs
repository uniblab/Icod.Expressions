	[Fact]
	public void CompiledUnsetPolicyOwnsFlagsSourceLabelsAndNonparticipation() {
		const string pattern = @"(A)?\1(*MARK:# [])";
		var source = Encoding.ASCII.GetBytes( pattern );
		var options = Options( true, 3 );
		var subject = Array.Empty<byte>();
		var reference = Reference( pattern, true, options );
		AssertLiteral( reference, subject, "0:0,-" );
		var result = PcreByteCompiler.Compile( source, options );
		Assert.True( result.IsSuccess );
		Array.Fill( source, (byte)'x' );
		SetSelection( options, false );
		Compare( reference, subject, 0, result.Pattern!.Match( subject ), "owned unset policy" );
