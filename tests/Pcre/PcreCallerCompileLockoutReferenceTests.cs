	[Fact]
	public void AllowedPoliciesKeepCanonicalWorkAndCancellation() {
		var source = "(A|AA)+B"u8.ToArray();
		var subject = "AAA"u8.ToArray();
		var reference = Reference( source, 7, 0 );
		AssertLiteral( reference, subject, "", "" );
		var steps = new List<int>();
		var options = Options( 7, 0 ) with { WorkObserver = steps.Add };
		Compare( reference, subject, 0, Compile( source, options ).Match( subject ), "caller-policy work" );
		Assert.Equal( Enumerable.Range( 1, steps.Count ), steps );
		Assert.True( steps.Count > 2 );
		var limited = Compile( source, options with { MatchWorkLimit = steps.Count - 1 } ).Match( subject );
		Assert.Equal( PcreByteDiagnosticCode.MatchWorkLimitExceeded, limited.Diagnostic?.Code );
		Assert.Null( limited.Match );
		using var cancellation = new CancellationTokenSource();
		var compiled = Compile( source, options with { WorkObserver = count => { if ( count == 2 ) { cancellation.Cancel(); } } } );
		Assert.Throws<OperationCanceledException>( () => compiled.Match( subject, 0, cancellation.Token ) );
	}

	[Fact]
	public void CompiledPatternsOwnSourceAndDiscardCompileTimePolicyObjects() {
		var source = "(?<x>A)\\k<x>"u8.ToArray();
		var subject = "AA"u8.ToArray();
		var reference = Reference( source, 7, 0 );
		AssertLiteral( reference, subject, "0:2,0:1", "" );
		var options = Options( 7, 0 );
		var compiled = Compile( source, options );
		Array.Fill( source, (byte)'x' );
		typeof( PcreByteOptions ).GetProperty( nameof( PcreByteOptions.Utf8 ) )!.SetValue( options, true );
		typeof( PcreByteOptions ).GetProperty( nameof( PcreByteOptions.Ucp ) )!.SetValue( options, true );
		Compare( reference, subject, 0, compiled.Match( subject ), "owned source and compile policies" );
	}

	[Fact]
	public void ExistingInvalidWorkAndCancellationPrecedeCallerRestrictions() {
		var options = Options( 7, 7 ) with { MatchWorkLimit = 0 };
		var source = "(*UTF)(*UCP)\\C"u8.ToArray();
		var result = PcreByteCompiler.Compile( source, options );
		Assert.Equal( PcreByteDiagnosticCode.InvalidWorkLimit, result.Diagnostic?.Code );
		Assert.Equal( 0, result.Diagnostic?.ByteOffset );
		Assert.Null( result.Pattern );
		using var cancellation = new CancellationTokenSource();
		cancellation.Cancel();
		Assert.Throws<OperationCanceledException>( () => PcreByteCompiler.Compile( source, options, cancellation.Token ) );
		Assert.Throws<OperationCanceledException>( () => PcreByteCompiler.Compile( new byte[] { 0xFF }, Options( 7, 7 ), cancellation.Token ) );
	}

	[Fact]
	public void CallerPoliciesPreserveSharedStructuralQuotas() {
		var patterns = new[] {
			String.Concat( String.Concat( Enumerable.Repeat( "()", 256 ) ), "A" ),
			String.Concat( String.Concat( Enumerable.Repeat( "()", 257 ) ), "A" ),
			String.Concat( new string( '(', 257 ), "A", new string( ')', 257 ) ), "A{4096}"
		};
		var references = patterns.Select( pattern => Reference( Encoding.ASCII.GetBytes( pattern ), 7, 0 ) ).ToArray();
		Compare( references[0], "A"u8.ToArray(), 0, Compile( Encoding.ASCII.GetBytes( patterns[0] ), Options( 7, 0 ) ).Match( "A"u8.ToArray() ), "full capture capacity" );
		var codes = new[] { PcreByteDiagnosticCode.PatternCaptureLimitExceeded, PcreByteDiagnosticCode.PatternDepthLimitExceeded, PcreByteDiagnosticCode.PatternRepeatLimitExceeded };
		for ( var index = 1; index < patterns.Length; index++ ) {
			var result = PcreByteCompiler.Compile( Encoding.ASCII.GetBytes( patterns[index] ), Options( 7, 0 ) );
			Assert.Equal( codes[index - 1], result.Diagnostic?.Code );
			Assert.Null( result.Pattern );
		}
	}

