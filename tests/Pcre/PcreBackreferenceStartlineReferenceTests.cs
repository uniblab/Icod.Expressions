	[Fact]
	public void BackreferenceSearchKeepsCanonicalWorkCancellationAndLimits() {
		const string pattern = @"(*ANY)(?m)^()\1B";
		var options = Options( false, false );
		var reference = Reference( pattern, options );
		var subject = Convert.FromHexString( "E280A842" );
		AssertLiteral( reference, subject, 1, "" );
		var steps = new List<int>();
		var compiled = Compile( pattern, options with { WorkObserver = steps.Add } );
		Compare( reference, subject, 1, compiled.Match( subject, 1 ), "line-start work" );
		Assert.Equal( Enumerable.Range( 1, steps.Count ), steps );
		Assert.True( steps.Count >= 2 );
		var limited = Compile( pattern, options with { MatchWorkLimit = steps.Count - 1 } ).Match( subject, 1 );
		Assert.Equal( PcreByteDiagnosticCode.MatchWorkLimitExceeded, limited.Diagnostic?.Code );
		Assert.Null( limited.Match );
		using var cancellation = new CancellationTokenSource();
		var cancellable = Compile( pattern, options with { WorkObserver = count => { if ( count == 2 ) { cancellation.Cancel(); } } } );
		Assert.Throws<OperationCanceledException>( () => cancellable.Match( subject, 1, cancellation.Token ) );
		Assert.Throws<OperationCanceledException>( () => PcreByteCompiler.Compile( Encoding.ASCII.GetBytes( pattern ), options, cancellation.Token ) );
	}

