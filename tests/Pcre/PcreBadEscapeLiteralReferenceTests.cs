	[Fact]
	public void RecoveryRetainsCanonicalWorkLimitsAndCancellation() {
		var sources = new[] { Encoding.ASCII.GetBytes( @"\j(A|AA)+B" ), Encoding.ASCII.GetBytes( "j(A|AA)+B" ) };
		var references = sources.Select( source => Reference( source, true, 1 ) ).ToArray();
		var subject = "jAAAB"u8.ToArray();
		foreach ( var reference in references ) { AssertLiteral( reference, subject, 0, "0:5,3:1", "" ); }
		var recovered = new List<int>();
		var canonical = new List<int>();
		var options = Options( true, 1 ) with { WorkObserver = recovered.Add };
		Compare( references[0], subject, 0, Compile( sources[0], options ).Match( subject ), "recovered work" );
		Compare( references[1], subject, 0, Compile( sources[1], Options( true, 1 ) with { WorkObserver = canonical.Add } ).Match( subject ), "canonical work" );
		Assert.Equal( canonical, recovered );
		Assert.Equal( Enumerable.Range( 1, recovered.Count ), recovered );
		Assert.True( recovered.Count > 2 );
		var limited = Compile( sources[0], options with { MatchWorkLimit = recovered.Count - 1 } ).Match( subject );
		Assert.Equal( PcreByteDiagnosticCode.MatchWorkLimitExceeded, limited.Diagnostic?.Code );
		Assert.Null( limited.Match );
		using var cancellation = new CancellationTokenSource();
		var compiled = Compile( sources[0], options with { WorkObserver = count => { if ( count == 2 ) { cancellation.Cancel(); } } } );
		Assert.Throws<OperationCanceledException>( () => compiled.Match( subject, 0, cancellation.Token ) );
		Assert.Throws<OperationCanceledException>( () => PcreByteCompiler.Compile( sources[0], options, cancellation.Token ) );
	}

