	[Fact]
	public void SkipRetainsFrameLimitsWholeSourceAdmissionAndStrictUtfValidation() {
		var compiled = Compile( "(a(*SKIP))*b", new() );
		Assert.NotNull( compiled.Match( String.Concat( new string( 'a', 100 ), "b" ).AsMemory() ).Match );
		Assert.Equal( PcreWordDiagnosticCode.MatchDepthLimitExceeded,
			compiled.Match( String.Concat( new string( 'a', 1100 ), "b" ).AsMemory() ).Diagnostic?.Code );
		Assert.Equal( "0:2,0:1", Spans( compiled.Match( "ab".AsMemory() ).Match ) );
		foreach ( var verb in new[] { "(*SKIP)", "(*SKIP:)" } ) {
			foreach ( var suffix in new[] { "?", "*", "{0}", "{1,2}" } ) {
				Assert.Equal( PcreWordDiagnosticCode.InvalidSyntax,
					PcreWordSequenceCompiler.CompileSequence( String.Concat( verb, suffix ).AsMemory() ).Diagnostic?.Code );
			}
			foreach ( var suffix in new[] { "(*sr:a)", "(*asr:a)", "\\K", "\\X", "(?:a){65}", "(?=(*sr:a)){0}" } ) {
				Assert.Equal( PcreWordDiagnosticCode.UnsupportedSyntax,
					PcreWordSequenceCompiler.CompileSequence( String.Concat( verb, suffix ).AsMemory() ).Diagnostic?.Code );
			}
		}
		Assert.Equal( PcreWordDiagnosticCode.InvalidUtf16Pattern,
			PcreWordSequenceCompiler.CompileSequence( "(*SKIP)(*MARK:\ud800)".AsMemory(), new() { Utf16 = true } ).Diagnostic?.Code );
		Assert.Equal( PcreWordDiagnosticCode.InvalidUtf16Subject,
			Compile( "aa(*SKIP)(*F)|()", new() { Utf16 = true } ).Match( "aa\udfff".AsMemory() ).Diagnostic?.Code );
		using var cancelled = new CancellationTokenSource(); cancelled.Cancel();
		Assert.Throws<OperationCanceledException>( () => PcreWordSequenceCompiler.CompileSequence( "(*SKIP)".AsMemory(), cancellationToken: cancelled.Token ) );
	}

	[Fact]
	public async Task SkipRestartsKeepOriginalViewsAndIndependentOwnedResults() {
		var source = "(😀)+(*SKIP)(*F)|(b)(*MARK:é😀)".ToCharArray();
		var owned = PcreWordSequenceCompiler.CompileSequence( source.AsMemory(), new() { Utf16 = true, Policy = new() { Anchored = true } } );
