				new() { Utf8 = true, Ucp = ucp } );
			Assert.Equal( PcreByteDiagnosticCode.PatternRepeatLimitExceeded, expansion.Diagnostic?.Code );
			Assert.Equal( atom.Length, expansion.Diagnostic?.ByteOffset );
			var numeric = PcreByteCompiler.Compile( Encoding.ASCII.GetBytes( String.Concat( atom, "{0,65536}A" ) ),
				new() { Utf8 = true, Ucp = ucp } );
			Assert.Equal( PcreByteDiagnosticCode.InvalidSyntax, numeric.Diagnostic?.Code );
			Assert.Equal( atom.Length, numeric.Diagnostic?.ByteOffset );
		}
	}

