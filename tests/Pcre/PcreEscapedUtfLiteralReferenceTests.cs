	private static PcreByteOptions Options( int mode ) => new() {
		Utf8 = ( mode & 1 ) != 0, Ucp = ( mode & 2 ) != 0, MatchInvalidUtf = ( mode & 4 ) != 0, Caseless = ( mode & 8 ) != 0,
		BadEscapeIsLiteral = ( mode & 16 ) != 0, AltBsux = ( mode & 32 ) != 0, ExtraAltBsux = ( mode & 64 ) != 0,
		AltVerbNames = ( mode & 128 ) != 0, Extended = ( mode & 256 ) != 0, ExtendedMore = ( mode & 512 ) != 0,
		MatchWord = ( mode & 1024 ) != 0, MatchLine = ( mode & 2048 ) != 0, NeverUtf = ( mode & 4096 ) != 0,
		NeverUcp = ( mode & 8192 ) != 0, AltExtendedClass = ( mode & 16384 ) != 0, AllowLookaroundBackslashK = ( mode & 32768 ) != 0,
		AllowSurrogateEscapes = ( mode & 65536 ) != 0
	};
	private static PcreRegex8Bit Reference( byte[] source, int mode ) => new( source, Encoding.UTF8, new PcreRegexSettings {
		Options = PcreOptions.Compiled | (PcreOptions)( ( ( mode & 1 ) != 0 ? 0x80000u : 0u ) | ( ( mode & 2 ) != 0 ? 0x20000u : 0u )
			| ( ( mode & 4 ) != 0 ? 0x4000000u : 0u ) | ( ( mode & 8 ) != 0 ? 8u : 0u ) | ( ( mode & 32 ) != 0 ? 2u : 0u )
			| ( ( mode & 128 ) != 0 ? 0x400000u : 0u ) | ( ( mode & 768 ) != 0 ? 0x80u : 0u ) | ( ( mode & 512 ) != 0 ? 0x1000000u : 0u )
			| ( ( mode & 4096 ) != 0 ? 0x1000u : 0u ) | ( ( mode & 8192 ) != 0 ? 0x800u : 0u ) | ( ( mode & 16384 ) != 0 ? 0x8000000u : 0u ) ),
		ExtraCompileOptions = (PcreExtraCompileOptions)( ( ( mode & 16 ) != 0 ? 2 : 0 ) | ( ( mode & 64 ) != 0 ? 0x20 : 0 )
			| ( ( mode & 1024 ) != 0 ? 4 : 0 ) | ( ( mode & 2048 ) != 0 ? 8 : 0 ) | ( ( mode & 32768 ) != 0 ? 64 : 0 ) | ( ( mode & 65536 ) != 0 ? 1 : 0 ) ), ParensLimit = 512
	} );
	private static PcreCompiledBytePattern Compile( byte[] source, PcreByteOptions options ) {
		var actual = PcreByteCompiler.Compile( source, options );
		Assert.True( actual.IsSuccess, $"{Encoding.UTF8.GetString( source )}: {actual.Diagnostic?.Message}" );
		return Assert.IsType<PcreCompiledBytePattern>( actual.Pattern );
	}
	private static void AssertLiteral( PcreRegex8Bit reference, byte[] subject, int offset, string spans, string mark ) {
		var match = reference.Match( subject, offset );
		Assert.Equal( spans.Length > 0, match.Success );
		if ( !match.Success ) { return; }
		Assert.Equal( mark, Convert.ToHexString( match.Mark.ToArray() ) );
		var groups = spans.Split( ',' );
		Assert.Equal( groups.Length, match.Groups.Count );
		for ( var group = 0; group < groups.Length; group++ ) {
			var capture = match.Groups[group];
			Assert.Equal( groups[group], capture.Success ? $"{capture.Index}:{capture.EndIndex - capture.Index}" : "-" );
		}
	}
	private static void Compare( PcreRegex8Bit reference, byte[] subject, int offset, PcreByteMatchResult actual, string context ) {
		var expected = reference.Match( subject, offset );
		Assert.True( actual.IsSuccess, $"{context}: {actual.Diagnostic?.Message}" );
		Assert.Equal( expected.Success ? expected.Index : -1, actual.Match?.ByteIndex ?? -1 );
		if ( !expected.Success ) { return; }
		Assert.Equal( expected.EndIndex - expected.Index, actual.Match!.ByteLength );
		Assert.Equal( expected.Mark.ToArray(), actual.Match.MarkName.ToArray() );
		Assert.Equal( expected.Groups.Count, actual.Match.Captures.Count );
		for ( var group = 0; group < expected.Groups.Count; group++ ) {
			var capture = expected.Groups[group];
			Assert.Equal( capture.Success ? new PcreByteCapture( capture.Index, capture.EndIndex - capture.Index ) : null, actual.Match.Captures[group] );
		}
	}
