		Assert.Equal( "4:1,-,4:1", Spans( saved.Match ) ); Assert.Equal( "é😀", saved.Match!.MarkName );
		Assert.Equal( "__😀😀b__", new string( input ) );
		var results = await Task.WhenAll( Enumerable.Range( 0, 64 ).Select( index => Task.Run( () =>
			owned.Pattern.Match( ( index % 2 == 0 ? "😀b" : "😀x" ).AsMemory() ) ) ) );
