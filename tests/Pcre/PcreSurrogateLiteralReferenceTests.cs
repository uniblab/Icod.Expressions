	[Fact]
	public void TolerantLiteralConsumptionUsesSharedWorkAndCancellation() {
		var source = Encoding.ASCII.GetBytes( @"(\x{D800}|A)+B" );
		var subject = Convert.FromHexString( "EDA08041414142" );
		var reference = Reference( source, 7 );
		AssertLiteral( reference, subject, 0, "0:7,5:1", "" );
		var steps = new List<int>();
		var options = Options( 7 ) with { WorkObserver = steps.Add };
		Compare( reference, subject, 0, Compile( source, options ).Match( subject ), "tolerant literal work" );
		Assert.Equal( Enumerable.Range( 1, steps.Count ), steps );
		Assert.True( steps.Count > 2 );
		var limited = Compile( source, options with { MatchWorkLimit = steps.Count - 1 } ).Match( subject );
		Assert.Equal( PcreByteDiagnosticCode.MatchWorkLimitExceeded, limited.Diagnostic?.Code );
		Assert.Null( limited.Match );
		using var cancellation = new CancellationTokenSource();
		var compiled = Compile( source, options with { WorkObserver = count => { if ( count == 2 ) { cancellation.Cancel(); } } } );
		Assert.Throws<OperationCanceledException>( () => compiled.Match( subject, 0, cancellation.Token ) );
	}

	private static readonly string[] OffsetBodies = [@"\x{D800}?A", @"(?<=\x{D800}{1,2})A", @"[\x{D800}]", @"(?:\x{D800}|.)", @"\x{D800}?", @"\x{D800}\X"];
	private static PcreByteOptions Options( int mode, bool uts = false ) => new() {
		AllowSurrogateEscapes = true, Utf8 = ( mode & 1 ) != 0, Ucp = ( mode & 2 ) != 0,
		MatchInvalidUtf = ( mode & 4 ) != 0, Caseless = ( mode & 8 ) != 0, AltExtendedClass = uts
	};
	private static PcreRegex8Bit Reference( byte[] source, int mode, bool uts = false, bool names = false ) => new(
		source, Encoding.UTF8, new PcreRegexSettings {
			Options = PcreOptions.Compiled | (PcreOptions)( ( ( mode & 1 ) != 0 ? 0x80000u : 0u ) | ( ( mode & 2 ) != 0 ? 0x20000u : 0u )
				| ( ( mode & 4 ) != 0 ? 0x4000000u : 0u ) | ( ( mode & 8 ) != 0 ? 8u : 0u ) | ( uts ? 0x8000000u : 0u ) | ( names ? 0x400000u : 0u ) ),
			ExtraCompileOptions = (PcreExtraCompileOptions)1, ParensLimit = 512
		} );
	private static PcreCompiledBytePattern Compile( byte[] source, PcreByteOptions options ) {
		var actual = PcreByteCompiler.Compile( source, options );
		Assert.True( actual.IsSuccess, $"{Encoding.UTF8.GetString( source )}: {actual.Diagnostic?.Message}" );
		return Assert.IsType<PcreCompiledBytePattern>( actual.Pattern );
	}
	private static void AssertLiteral( PcreRegex8Bit reference, byte[] subject, int offset, string spans, string mark ) {
		var match = reference.Match( subject, offset );
		Assert.Equal( spans.Length > 0, match.Success );
		if ( !match.Success ) { return; }
		Assert.Equal( mark, Convert.ToHexString( match.Mark.ToArray() ) );
		var groups = spans.Split( ',' );
		Assert.Equal( groups.Length, match.Groups.Count );
		for ( var group = 0; group < groups.Length; group++ ) {
			var capture = match.Groups[group];
			Assert.Equal( groups[group], capture.Success ? $"{capture.Index}:{capture.Length}" : "-" );
		}
	}
	private static void Compare( PcreRegex8Bit reference, byte[] subject, int offset, PcreByteMatchResult actual, string context ) {
		var expected = reference.Match( subject, offset );
		Assert.True( actual.IsSuccess, $"{context}: {actual.Diagnostic?.Message}" );
		Assert.True( ( expected.Success ? expected.Index : -1 ) == ( actual.Match?.ByteIndex ?? -1 ), context );
		if ( !expected.Success ) { return; }
		Assert.Equal( expected.Length, actual.Match!.ByteLength );
		Assert.Equal( expected.Mark.ToArray(), actual.Match.MarkName.ToArray() );
		Assert.Equal( expected.Groups.Count, actual.Match.Captures.Count );
		for ( var group = 0; group < expected.Groups.Count; group++ ) {
			var capture = expected.Groups[group];
			Assert.Equal( capture.Success ? new PcreByteCapture( capture.Index, capture.Length ) : null, actual.Match.Captures[group] );
		}
	}
