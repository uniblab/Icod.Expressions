	[Theory]
	[InlineData( 1 )]
	[InlineData( 3 )]
	[InlineData( 5 )]
	[InlineData( 7 )]
	public void UtfRestrictionWinsBeforeEveryPossiblePatternOctet( int mask ) {
		var sources = new List<(byte[] Source, int Mode, int Offset)>();
		foreach ( var prefix in new[] { "", "(*UTF)", "(*LF)(*UTF8)(*UCP)" } ) {
			for ( var value = 0; value < 256; value++ ) {
				var source = Encoding.ASCII.GetBytes( prefix ).Concat( new[] { (byte)value } ).ToArray();
				sources.Add( (source, prefix.Length == 0 ? 1 : 0, prefix.Length) );
			}
		}
		var native = sources.Select( item => Assert.Throws<PcrePatternException>( () => Reference( item.Source, mask, item.Mode ) ) ).ToArray();
		for ( var index = 0; index < sources.Count; index++ ) {
			Assert.Equal( 174, (int)native[index].ErrorCode );
			Assert.EndsWith( $" at offset {sources[index].Offset}.", native[index].Message );
		}
		foreach ( var item in sources ) {
			var result = PcreByteCompiler.Compile( item.Source, Options( mask, item.Mode ) );
			Assert.Equal( PcreByteDiagnosticCode.InvalidSyntax, result.Diagnostic?.Code );
			Assert.Equal( item.Offset, result.Diagnostic?.ByteOffset );
			Assert.Contains( "UTF", result.Diagnostic!.Message );
			Assert.Contains( "disabled by the caller", result.Diagnostic.Message );
			Assert.Null( result.Pattern );
		}
	}

