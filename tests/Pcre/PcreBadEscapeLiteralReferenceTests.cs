	[Fact]
	public void RecoveryRetainsCaptureDepthAndExpansionCeilings() {
		var patterns = new[] {
			String.Concat( @"\j", String.Concat( Enumerable.Repeat( "()", 256 ) ), "A" ),
			String.Concat( @"\j", String.Concat( Enumerable.Repeat( "()", 257 ) ), "A" ),
			String.Concat( @"\j", new string( '(', 257 ), "A", new string( ')', 257 ) ), @"\j{4096}"
		};
		var references = patterns.Select( pattern => Reference( Encoding.ASCII.GetBytes( pattern ), true, 1 ) ).ToArray();
		var subject = "jA"u8.ToArray();
		Compare( references[0], subject, 0, Compile( Encoding.ASCII.GetBytes( patterns[0] ), Options( true, 1 ) ).Match( subject ), "full capture capacity" );
		var codes = new[] { PcreByteDiagnosticCode.PatternCaptureLimitExceeded, PcreByteDiagnosticCode.PatternDepthLimitExceeded, PcreByteDiagnosticCode.PatternRepeatLimitExceeded };
		for ( var index = 1; index < patterns.Length; index++ ) {
			var actual = PcreByteCompiler.Compile( Encoding.ASCII.GetBytes( patterns[index] ), Options( true, 1 ) );
			Assert.Equal( codes[index - 1], actual.Diagnostic?.Code );
			Assert.Null( actual.Pattern );
		}
	}

	[Fact]
	public void SourceUtfAndCallerModeGuardsPrecedeEscapeRecovery() {
		var prefix = "\\j"u8.ToArray();
		var source = prefix.Concat( new byte[] { 0xFF } ).ToArray();
		foreach ( var enabled in new[] { false, true } ) {
			var native = Assert.Throws<PcrePatternException>( () => Reference( source, enabled, 1 ) );
			Assert.Equal( -23, (int)native.ErrorCode );
			Assert.EndsWith( " at offset 2.", native.Message );
			var actual = PcreByteCompiler.Compile( source, Options( enabled, 1 ) );
			Assert.Equal( PcreByteDiagnosticCode.InvalidUtf8Pattern, actual.Diagnostic?.Code );
			Assert.Equal( 2, actual.Diagnostic?.ByteOffset );
			Assert.Null( actual.Pattern );
		}
		var sources = new[] { "\\j"u8.ToArray(), "(*UCP)\\j"u8.ToArray() };
		var flags = new uint[] { 0x1000, 0x800 };
		var nativeCodes = new[] { 174, 175 };
		var offsets = new[] { 0, 6 };
		var nativeErrors = sources.Select( ( value, index ) => Assert.Throws<PcrePatternException>( () => Reference( value, true, 1, flags[index] ) ) ).ToArray();
		for ( var index = 0; index < sources.Length; index++ ) {
			Assert.Equal( nativeCodes[index], (int)nativeErrors[index].ErrorCode );
			Assert.EndsWith( $" at offset {offsets[index]}.", nativeErrors[index].Message );
		}
		var options = new[] { Options( true, 1 ) with { NeverUtf = true }, Options( true, 1 ) with { NeverUcp = true } };
		for ( var index = 0; index < sources.Length; index++ ) {
			var actual = PcreByteCompiler.Compile( sources[index], options[index] );
			Assert.Equal( PcreByteDiagnosticCode.InvalidSyntax, actual.Diagnostic?.Code );
			Assert.Equal( offsets[index], actual.Diagnostic?.ByteOffset );
			Assert.Null( actual.Pattern );
		}
	}

	[Fact]
	public void ValidEscapedScalarsAndPendingCompilerGuardsStaySeparate() {
		foreach ( var enabled in new[] { false, true } ) {
			foreach ( var source in new[] { "\\C"u8.ToArray(), "(*BAD_ESCAPE_IS_LITERAL)A"u8.ToArray() } ) {
				var actual = PcreByteCompiler.Compile( source, Options( enabled, 1 ) );
				Assert.Equal( PcreByteDiagnosticCode.UnsupportedSyntax, actual.Diagnostic?.Code );
				Assert.Equal( 0, actual.Diagnostic?.ByteOffset );
				Assert.Null( actual.Pattern );
			}
			var escaped = Encoding.UTF8.GetBytes( @"\é" );
			var subject = "é"u8.ToArray();
			var reference = Reference( escaped, enabled, 1 );
			AssertLiteral( reference, subject, 0, "0:2", "" );
			Compare( reference, subject, 0, Compile( escaped, Options( enabled, 1 ) ).Match( subject ), "valid scalar independent of recovery" );
			var guarded = PcreByteCompiler.Compile( "\\x{D800}\\B"u8.ToArray(), Options( enabled, 4103 ) );
			Assert.Equal( PcreByteDiagnosticCode.UnsupportedSyntax, guarded.Diagnostic?.Code );
			Assert.Contains( "tolerant surrogate literals", guarded.Diagnostic!.Message );
			Assert.Null( guarded.Pattern );
		}
	}

	[Fact]
	public void PerlClassSuppressionRestoresAndSuccessfulEscapesKeepTheirMeaning() {
		var sources = new[] { Encoding.ASCII.GetBytes( @"(?[ [A] ])\j" ), Encoding.ASCII.GetBytes( @"\p{L}" ), Encoding.ASCII.GetBytes( @"\o{101}" ), Encoding.ASCII.GetBytes( @"\x{41}" ) };
		var subjects = new[] { "Aj"u8.ToArray(), "A"u8.ToArray(), "A"u8.ToArray(), "A"u8.ToArray() };
