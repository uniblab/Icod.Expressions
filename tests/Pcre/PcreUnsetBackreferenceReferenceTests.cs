		Assert.NotNull( actual );
		Assert.Null( actual.Captures[1] );
		Assert.Equal( "# []", Encoding.ASCII.GetString( actual.MarkName.Span ) );
		Assert.Null( Compile( pattern, Options( false, 3 ) ).Match( subject ).Match );
	}

