	}

	[Fact]
	public void GuardDoesNotBypassCaptureDepthOrExpansionCeilings() {
		var prefix = @"\Q(?C)\E";
		var patterns = new[] {
			String.Concat( prefix, String.Concat( Enumerable.Repeat( "()", 256 ) ), "A" ),
			String.Concat( prefix, String.Concat( Enumerable.Repeat( "()", 257 ) ), "A" ),
			String.Concat( prefix, String.Concat( Enumerable.Repeat( "(?:", 257 ) ), "A", new string( ')', 257 ) ),
			String.Concat( prefix, "A{4096}" )
		};
		var references = patterns.Select( pattern => Reference( Encoding.ASCII.GetBytes( pattern ), true, 1 ) ).ToArray();
		var subject = "(?C)A"u8.ToArray();
		AssertLiteral( references[0], subject, 0, String.Concat( "0:5,", String.Join( ",", Enumerable.Repeat( "4:0", 256 ) ) ), "" );
		Compare( references[0], subject, 0, Compile( Encoding.ASCII.GetBytes( patterns[0] ), Options( true, 1 ) ).Match( subject ), "capture capacity" );
		var codes = new[] { PcreByteDiagnosticCode.PatternCaptureLimitExceeded, PcreByteDiagnosticCode.PatternDepthLimitExceeded, PcreByteDiagnosticCode.PatternRepeatLimitExceeded };
		for ( var index = 1; index < patterns.Length; index++ ) {
			var actual = PcreByteCompiler.Compile( Encoding.ASCII.GetBytes( patterns[index] ), Options( true, 1 ) );
			Assert.Equal( codes[index - 1], actual.Diagnostic?.Code );
			Assert.Null( actual.Pattern );
		}
	}

	[Fact]
	public void FullCaptureAndDepthPrefixesStillRejectDispatchedCallouts() {
		var prefixes = new[] { String.Concat( Enumerable.Repeat( "()", 256 ) ), String.Concat( Enumerable.Repeat( "(?:", 256 ) ) };
		for ( var index = 0; index < prefixes.Length; index++ ) {
			var source = Encoding.ASCII.GetBytes( String.Concat( prefixes[index], "(?C1)", index == 0 ? "" : new string( ')', 256 ) ) );
			var native = Assert.Throws<PcrePatternException>( () => Reference( source, true, 1 ) );
			Assert.Equal( 203, (int)native.ErrorCode );
			Assert.EndsWith( $" at offset {prefixes[index].Length + 3}.", native.Message );
			var actual = PcreByteCompiler.Compile( source, Options( true, 1 ) );
			Assert.Equal( PcreByteDiagnosticCode.InvalidSyntax, actual.Diagnostic?.Code );
			Assert.Equal( prefixes[index].Length, actual.Diagnostic?.ByteOffset );
			Assert.Contains( "caller", actual.Diagnostic!.Message );
			Assert.Null( actual.Pattern );
		}
	}

	private static PcreByteOptions Options( bool enabled, int mode ) {
		var options = new PcreByteOptions { Utf8 = ( mode & 1 ) != 0, Ucp = ( mode & 2 ) != 0, MatchInvalidUtf = ( mode & 4 ) != 0,
			Caseless = ( mode & 8 ) != 0, AltExtendedClass = ( mode & 16 ) != 0, AltVerbNames = ( mode & 32 ) != 0,
			BadEscapeIsLiteral = ( mode & 64 ) != 0, NeverBackslashC = ( mode & 128 ) != 0, NeverUtf = ( mode & 256 ) != 0, NeverUcp = ( mode & 512 ) != 0 };
		// Keep tests-only RED executable before the caller prohibition exists.
		if ( enabled ) { typeof( PcreByteOptions ).GetProperty( "NeverCallout" )?.SetValue( options, true ); }
		return options;
	}
	private static PcreRegex8Bit Reference( byte[] source, bool enabled, int mode ) => new(
		source, Encoding.UTF8, new PcreRegexSettings {
			Options = PcreOptions.Compiled | (PcreOptions)( ( ( mode & 1 ) != 0 ? 0x80000u : 0u ) | ( ( mode & 2 ) != 0 ? 0x20000u : 0u )
				| ( ( mode & 4 ) != 0 ? 0x4000000u : 0u ) | ( ( mode & 8 ) != 0 ? 8u : 0u ) | ( ( mode & 16 ) != 0 ? 0x8000000u : 0u )
				| ( ( mode & 32 ) != 0 ? 0x400000u : 0u ) | ( ( mode & 128 ) != 0 ? 0x100000u : 0u ) | ( ( mode & 256 ) != 0 ? 0x1000u : 0u )
				| ( ( mode & 512 ) != 0 ? 0x800u : 0u ) ),
			ExtraCompileOptions = (PcreExtraCompileOptions)( ( enabled ? 0x8000 : 0 ) | ( ( mode & 64 ) != 0 ? 2 : 0 ) ), ParensLimit = 512
		} );
	private static PcreCompiledBytePattern Compile( byte[] source, PcreByteOptions options ) {
		var actual = PcreByteCompiler.Compile( source, options );
		Assert.True( actual.IsSuccess, $"{Encoding.UTF8.GetString( source )}: {actual.Diagnostic?.Message}" );
		return Assert.IsType<PcreCompiledBytePattern>( actual.Pattern );
	}
	private static void AssertLiteral( PcreRegex8Bit reference, byte[] subject, int offset, string spans, string mark ) {
		var match = reference.Match( subject, offset );
		Assert.Equal( spans.Length > 0, match.Success );
		if ( !match.Success ) { return; }
		Assert.Equal( mark, Convert.ToHexString( match.Mark.ToArray() ) );
		var groups = spans.Split( ',' );
		Assert.Equal( groups.Length, match.Groups.Count );
		for ( var group = 0; group < groups.Length; group++ ) {
			var capture = match.Groups[group];
			Assert.Equal( groups[group], capture.Success ? $"{capture.Index}:{capture.Length}" : "-" );
		}
	}
	private static void Compare( PcreRegex8Bit reference, byte[] subject, int offset, PcreByteMatchResult actual, string context ) {
		var expected = reference.Match( subject, offset );
		Assert.True( actual.IsSuccess, $"{context}: {actual.Diagnostic?.Message}" );
		Assert.True( ( expected.Success ? expected.Index : -1 ) == ( actual.Match?.ByteIndex ?? -1 ), context );
		if ( !expected.Success ) { return; }
		Assert.Equal( expected.Length, actual.Match!.ByteLength );
		Assert.Equal( expected.Mark.ToArray(), actual.Match.MarkName.ToArray() );
		Assert.Equal( expected.Groups.Count, actual.Match.Captures.Count );
		for ( var group = 0; group < expected.Groups.Count; group++ ) {
			var capture = expected.Groups[group];
			Assert.Equal( capture.Success ? new PcreByteCapture( capture.Index, capture.Length ) : null, actual.Match.Captures[group] );
		}
	}
