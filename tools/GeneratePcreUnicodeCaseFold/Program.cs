using System.Globalization;
using System.Security.Cryptography;
using System.Text;

const string sourceHash = "FF8D8FEFBF123574205085D6714C36149EB946D717A0C585C27F0F4EF58C4183";
var verify = args.Length > 0 && args[0] == "--verify";
var paths = verify ? args[1..] : args;
if ( paths.Length != 2 ) {
	Console.Error.WriteLine( "Usage: GeneratePcreUnicodeCaseFold [--verify] CaseFolding.txt PcreUtf8CaseFold.Data.cs" );
	return 2;
}
var input = File.ReadAllBytes( paths[0] );
if ( Convert.ToHexString( SHA256.HashData( input ) ) != sourceHash ) {
	Console.Error.WriteLine( "Expected the pinned Unicode17.0.0 CaseFolding.txt SHA256." );
	return 1;
}
var mappings = new SortedDictionary<int, int>();
foreach ( var line in Encoding.UTF8.GetString( input ).Split( '\n' ) ) {
	var text = line.Split( '#' )[0].Trim();
	if ( text.Length == 0 ) { continue; }
	var fields = text.Split( ';' );
	if ( fields[1].Trim() is not ( "C" or "S" ) ) { continue; }
	var source = int.Parse( fields[0].Trim(), NumberStyles.HexNumber, CultureInfo.InvariantCulture );
	var target = int.Parse( fields[2].Trim(), NumberStyles.HexNumber, CultureInfo.InvariantCulture );
	if ( !Rune.IsValid( source ) || !Rune.IsValid( target ) || source == target || !mappings.TryAdd( source, target ) ) {
		throw new InvalidDataException( "Invalid or duplicate simple-case mapping." );
	}
}
foreach ( var pair in mappings ) {
	if ( mappings.ContainsKey( pair.Value ) ) { throw new InvalidDataException( "Simple-case mapping is not idempotent." ); }
	if ( pair.Key < 128 && ( pair.Key is < 'A' or > 'Z' || pair.Value != pair.Key + 32 ) ) {
		throw new InvalidDataException( "ASCII mapping differs from the runtime fast path." );
	}
}
var output = new StringBuilder();
void Line( string value = "" ) => output.Append( value ).Append( '\n' );
Line( "// <auto-generated />" );
Line( "// Unicode 17.0.0 CaseFolding.txt C/S mappings; regenerate with tools/GeneratePcreUnicodeCaseFold." );
Line( "// SHA256: " + sourceHash );
Line( "// Copyright © 2025 Unicode, Inc. See THIRD-PARTY-NOTICES.txt (Unicode License V3)." );
Line();
Line( "namespace Icod.Expressions.Pcre;" );
Line();
Line( "internal static partial class PcreUtf8CaseFold {" );
Line( "\t// Source scalar in the upper bits, target scalar in the low 21; ASCII uses the fast path." );
Line( "\tprivate static ReadOnlySpan<ulong> UnicodeMappings => [" );
var entries = mappings.Where( pair => pair.Key >= 128 ).Select( pair =>
	"0x" + ( ( (ulong)pair.Key << 21 ) | (uint)pair.Value ).ToString( "X16", CultureInfo.InvariantCulture ) + "UL" ).ToArray();
for ( var first = 0; first < entries.Length; first += 4 ) {
	Line( "\t\t" + string.Join( ", ", entries.Skip( first ).Take( 4 ) ) + "," );
}
Line( "\t];" );
Line( "}" );
var generated = new UTF8Encoding( false ).GetBytes( output.ToString() );
if ( verify ) {
	if ( !File.ReadAllBytes( paths[1] ).AsSpan().SequenceEqual( generated ) ) {
		Console.Error.WriteLine( "Generated Unicode simple-case mappings differ from the committed data." );
		return 1;
	}
	Console.WriteLine( $"Verified Unicode17 simple-case mappings: {mappings.Count} total, {entries.Length} non-ASCII." );
	return 0;
}
File.WriteAllBytes( paths[1], generated );
return 0;
