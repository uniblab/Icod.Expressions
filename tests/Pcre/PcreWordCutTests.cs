	[InlineData( "PRUNE" )]
	[InlineData( "COMMIT" )]
	public void CutsRetainSourceAdmissionStrictUtfAndTheFrameCeiling( string verb ) {
		var source = String.Concat( "(a(*", verb, ":N))*b" );
		var compiled = Compile( source, new() );
		Assert.NotNull( compiled.Match( String.Concat( new string( 'a', 100 ), "b" ).AsMemory() ).Match );
		Assert.Equal( PcreWordDiagnosticCode.MatchDepthLimitExceeded,
			compiled.Match( String.Concat( new string( 'a', 1100 ), "b" ).AsMemory() ).Diagnostic?.Code );
		Assert.Equal( "N", compiled.Match( "ab".AsMemory() ).Match!.MarkName );
		foreach ( var suffix in new[] { "?", "*", "{0}", "{1,2}" } ) {
			Assert.Equal( PcreWordDiagnosticCode.InvalidSyntax,
				PcreWordSequenceCompiler.CompileSequence( String.Concat( "(*", verb, ")", suffix ).AsMemory() ).Diagnostic?.Code );
		}
		foreach ( var suffix in new[] { "(*THEN)", "(*SKIP)", "\\X", "(?:a){65}" } ) {
			Assert.Equal( PcreWordDiagnosticCode.UnsupportedSyntax,
				PcreWordSequenceCompiler.CompileSequence( String.Concat( "(*", verb, ")", suffix ).AsMemory() ).Diagnostic?.Code );
		}
		Assert.Equal( PcreWordDiagnosticCode.InvalidUtf16Pattern,
			PcreWordSequenceCompiler.CompileSequence( String.Concat( "(*", verb, ":\ud800)" ).AsMemory(), new() { Utf16 = true } ).Diagnostic?.Code );
		Assert.Equal( PcreWordDiagnosticCode.InvalidUtf16Subject,
			Compile( source, new() { Utf16 = true } ).Match( "ab\udfff".AsMemory() ).Diagnostic?.Code );
		using var cancelled = new CancellationTokenSource(); cancelled.Cancel();
		Assert.Throws<OperationCanceledException>( () => PcreWordSequenceCompiler.CompileSequence( source.AsMemory(), cancellationToken: cancelled.Token ) );
	}

	[Theory]
	[InlineData( "PRUNE" )]
	[InlineData( "COMMIT" )]
	public async Task CutLabelsRemainOwnedAcrossConcurrentReuse( string verb ) {
		var source = String.Concat( "(?<x>😀)(*", verb, ":é😀)x" ).ToCharArray();
		var owned = PcreWordSequenceCompiler.CompileSequence( source.AsMemory(), new() { Utf16 = true } );
		Assert.True( owned.IsSuccess ); Array.Fill( source, 'z' );
		var saved = owned.Pattern!.Match( "__😀x__".AsMemory( 2, 3 ) );
		Assert.Equal( "0:3,0:2", Spans( saved.Match ) ); Assert.Equal( "é😀", saved.Match!.MarkName );
		var results = await Task.WhenAll( Enumerable.Range( 0, 64 ).Select( index => Task.Run( () =>
			owned.Pattern.Match( ( index % 2 == 0 ? "😀x" : "😀y" ).AsMemory() ) ) ) );
		for ( var index = 0; index < results.Length; index++ ) {
			Assert.True( results[index].IsSuccess ); Assert.Equal( index % 2 == 0, results[index].Match is not null );
			if ( results[index].Match is { } match ) { Assert.Equal( "é😀", match.MarkName ); }
		}
		Assert.Equal( "0:3,0:2", Spans( saved.Match ) ); Assert.Equal( "é😀", saved.Match.MarkName );
	}

