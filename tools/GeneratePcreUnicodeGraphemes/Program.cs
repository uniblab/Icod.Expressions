using System.Globalization;
using System.Security.Cryptography;
using System.Text;

string[] names = { "CR", "LF", "Control", "Extend", "Prepend", "SpacingMark", "L", "V", "T", "LV", "LVT", "Regional_Indicator", "Other", "ZWJ", "Extended_Pictographic" };
string[] hashes = {
	"D6B51D1D2AE5C33B451B7ED994B48F1F4DC62B2272A5831E7FD418514A6BAE89",
	"2CB2BB9455CDA83E8481541ECF5B6DFDA66A3BB89EFA3FA7C5297ECCF607B72B"
};
const string nativeHash = "FE5B7E8E4FEB352EA6F9EF976370BFCBB00B52A0466E32B0BC274D0F3B5D658D";
var verify = args.Length > 0 && args[0] == "--verify";
var paths = verify ? args[1..] : args;
if ( paths.Length != 3 ) {
	Console.Error.WriteLine( "Usage: GeneratePcreUnicodeGraphemes [--verify] GraphemeBreakProperty.txt emoji-data.txt PcreUnicodeGraphemes.Data.cs" );
	return 2;
}
var kinds = new byte[0x110000];
Array.Fill( kinds, (byte)12 ); // Other, including unassigned code points.
var assigned = new bool[kinds.Length];
for ( var file = 0; file < 2; file++ ) {
	var bytes = File.ReadAllBytes( paths[file] );
	if ( Convert.ToHexString( SHA256.HashData( bytes ) ) != hashes[file] ) {
		Console.Error.WriteLine( "Expected the pinned Unicode17 source SHA256: " + paths[file] );
		return 1;
	}
	foreach ( var raw in Encoding.UTF8.GetString( bytes ).Split( '\n' ) ) {
		var text = raw.Split( '#' )[0].Trim();
		if ( text.Length == 0 ) { continue; }
		var fields = text.Split( ';' ).Select( value => value.Trim() ).ToArray();
		if ( file == 1 && fields[1] != "Extended_Pictographic" ) { continue; }
		var id = Array.IndexOf( names, fields[1] );
		if ( id < 0 ) { throw new InvalidDataException( "Unknown break property." ); }
		var limits = fields[0].Split( "..", StringSplitOptions.None );
		var first = int.Parse( limits[0], NumberStyles.HexNumber, CultureInfo.InvariantCulture );
		var last = int.Parse( limits[^1], NumberStyles.HexNumber, CultureInfo.InvariantCulture );
		if ( first < 0 || first > last || last >= kinds.Length ) { throw new InvalidDataException( "Invalid break range." ); }
		for ( var scalar = first; scalar <= last; scalar++ ) {
			if ( file == 0 && assigned[scalar] || file == 1 && kinds[scalar] != 12 ) {
				throw new InvalidDataException( "Overlapping break properties." );
			}
			if ( id == 11 && scalar < 0x10000 ) { throw new InvalidDataException( "RI memo requires four-byte UTF8 scalars." ); }
			assigned[scalar] = true;
			kinds[scalar] = (byte)id;
		}
	}
}
var fingerprint = new byte[0x110000 - 0x800];
kinds.AsSpan( 0, 0xD800 ).CopyTo( fingerprint );
kinds.AsSpan( 0xE000 ).CopyTo( fingerprint.AsSpan( 0xD800 ) );
if ( Convert.ToHexString( SHA256.HashData( fingerprint ) ) != nativeHash ) {
	throw new InvalidDataException( "Unicode source classification differs from the pinned native fingerprint." );
}
var output = new StringBuilder();
void Line( string value = "" ) => output.Append( value ).Append( '\n' );
Line( "// <auto-generated />" );
Line( "// Unicode 17.0.0 GraphemeBreakProperty/emoji-data; tools/GeneratePcreUnicodeGraphemes." );
foreach ( var hash in hashes ) { Line( "// Source SHA256: " + hash ); }
Line( "// Native scalar break SHA256: " + nativeHash );
Line( "// Copyright © 2025 Unicode, Inc. See THIRD-PARTY-NOTICES.txt (Unicode License V3)." );
Line();
Line( "namespace Icod.Expressions.Pcre;" );
Line();
Line( "internal static partial class PcreUnicodeGraphemes {" );
Line( "\tprivate static ReadOnlySpan<byte> AsciiKinds => [" );
for ( var first = 0; first < 128; first += 16 ) {
	Line( "\t\t" + string.Join( ", ", kinds.Skip( first ).Take( 16 ).Select( value => value.ToString( CultureInfo.InvariantCulture ) ) ) + "," );
}
Line( "\t];" );
Line( "\t// Full partition from U+0080: inclusive end << 4 | break kind." );
Line( "\tprivate static ReadOnlySpan<uint> EndKinds => [" );
var entries = new List<string>();
for ( var scalar = 128; scalar < kinds.Length; scalar++ ) {
	if ( scalar + 1 < kinds.Length && kinds[scalar] == kinds[scalar + 1] ) { continue; }
	entries.Add( "0x" + ( ( (uint)scalar << 4 ) | kinds[scalar] ).ToString( "X8", CultureInfo.InvariantCulture ) + "U" );
}
for ( var first = 0; first < entries.Count; first += 8 ) { Line( "\t\t" + string.Join( ", ", entries.Skip( first ).Take( 8 ) ) + "," ); }
Line( "\t];" );
Line( "}" );
var generated = new UTF8Encoding( false ).GetBytes( output.ToString() );
if ( verify ) {
	if ( !File.ReadAllBytes( paths[2] ).AsSpan().SequenceEqual( generated ) ) {
		Console.Error.WriteLine( "Generated Unicode grapheme properties differ from committed data." );
		return 1;
	}
	Console.WriteLine( $"Verified Unicode17 graphemes: 128 ASCII entries, {entries.Count} ranges, native fingerprint {nativeHash}." );
	return 0;
}
File.WriteAllBytes( paths[2], generated );
return 0;
