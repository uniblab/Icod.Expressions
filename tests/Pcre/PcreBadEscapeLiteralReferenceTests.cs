		Compare( reference, subject, 0, Compile( source, Options( true, 1 ) ).Match( subject ), "failed reference transaction" );
	}

	[Fact]
	public void RecoveredPatternsOwnTheirSourceOptionsAndLabelData() {
		var source = Encoding.ASCII.GetBytes( @"\j(*MARK:K)(A)\1" );
