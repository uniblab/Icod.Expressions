using System.Globalization;
using System.Security.Cryptography;
using System.Text;

const string sourceHash = "D62E5BAB70CA74F099343F71224FA051CB1FDD61A1AB45C0488C44CFC0B6102E";
var verify = args.Length > 0 && args[0] == "--verify";
var paths = verify ? args[1..] : args;
if ( paths.Length != 2 ) {
	Console.Error.WriteLine( "Usage: GeneratePcreUnicodeCategories [--verify] DerivedGeneralCategory.txt PcreUnicodeCategories.Data.cs" );
	return 2;
}
var input = File.ReadAllBytes( paths[0] );
if ( Convert.ToHexString( SHA256.HashData( input ) ) != sourceHash ) {
	Console.Error.WriteLine( "Expected the pinned Unicode17.0.0 DerivedGeneralCategory.txt SHA256." );
	return 1;
}
// Explicit .NET UnicodeCategory value order, independent of enum spelling.
string[] names = {
	"Lu", "Ll", "Lt", "Lm", "Lo", "Mn", "Mc", "Me", "Nd", "Nl", "No", "Zs", "Zl", "Zp",
	"Cc", "Cf", "Cs", "Co", "Pc", "Pd", "Ps", "Pe", "Pi", "Pf", "Po", "Sm", "Sc", "Sk", "So", "Cn"
};
var categories = new byte[0x110000];
Array.Fill( categories, byte.MaxValue );
foreach ( var line in Encoding.UTF8.GetString( input ).Split( '\n' ) ) {
	var text = line.Split( '#' )[0].Trim();
	if ( text.Length == 0 ) { continue; }
	var fields = text.Split( ';' );
	var limits = fields[0].Trim().Split( "..", StringSplitOptions.None );
	var first = int.Parse( limits[0], NumberStyles.HexNumber, CultureInfo.InvariantCulture );
	var last = int.Parse( limits[^1], NumberStyles.HexNumber, CultureInfo.InvariantCulture );
	var category = Array.IndexOf( names, fields[1].Trim() );
	if ( category < 0 || first < 0 || first > last || last >= categories.Length ) {
		throw new InvalidDataException( "Invalid Unicode category range." );
	}
	for ( var scalar = first; scalar <= last; scalar++ ) {
		if ( categories[scalar] != byte.MaxValue ) { throw new InvalidDataException( "Overlapping Unicode category ranges." ); }
		categories[scalar] = (byte)category;
	}
}
if ( categories.Contains( byte.MaxValue ) ) { throw new InvalidDataException( "Incomplete Unicode category coverage." ); }
var output = new StringBuilder();
void Line( string value = "" ) => output.Append( value ).Append( '\n' );
Line( "// <auto-generated />" );
Line( "// Unicode 17.0.0 DerivedGeneralCategory.txt; regenerate with tools/GeneratePcreUnicodeCategories." );
Line( "// SHA256: " + sourceHash );
Line( "// Copyright © 2025 Unicode, Inc. See THIRD-PARTY-NOTICES.txt (Unicode License V3)." );
Line();
Line( "namespace Icod.Expressions.Pcre;" );
Line();
Line( "internal static partial class PcreUnicodeCategories {" );
Line( "\tprivate static ReadOnlySpan<byte> AsciiCategories => [" );
for ( var first = 0; first < 128; first += 16 ) {
	Line( "\t\t" + string.Join( ", ", categories.Skip( first ).Take( 16 ).Select( value => value.ToString( CultureInfo.InvariantCulture ) ) ) + "," );
}
Line( "\t];" );
Line();
Line( "\t// Each uint packs a range start in the upper bits and UnicodeCategory in the low five." );
Line( "\tprivate static ReadOnlySpan<uint> CategoryRanges => [" );
var entries = new List<string>();
for ( var scalar = 128; scalar < categories.Length; scalar++ ) {
	if ( scalar != 128 && categories[scalar] == categories[scalar - 1] ) { continue; }
	entries.Add( "0x" + ( ( (uint)scalar << 5 ) | categories[scalar] ).ToString( "X8", CultureInfo.InvariantCulture ) + "u" );
}
for ( var first = 0; first < entries.Count; first += 8 ) {
	Line( "\t\t" + string.Join( ", ", entries.Skip( first ).Take( 8 ) ) + "," );
}
Line( "\t];" );
Line( "}" );
var generated = new UTF8Encoding( false ).GetBytes( output.ToString() );
if ( verify ) {
	if ( !File.ReadAllBytes( paths[1] ).AsSpan().SequenceEqual( generated ) ) {
		Console.Error.WriteLine( "Generated Unicode categories differ from the committed data." );
		return 1;
	}
	Console.WriteLine( $"Verified Unicode17 categories: 128 ASCII entries, {entries.Count} ranges." );
	return 0;
}
File.WriteAllBytes( paths[1], generated );
return 0;
