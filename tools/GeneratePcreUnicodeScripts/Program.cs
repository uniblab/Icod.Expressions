using System.Globalization;
using System.Security.Cryptography;
using System.Text;

string[] hashes = {
	"9F5E50D3ABAEE7D6CE09480F325C706F485AE3240912527E651954D2D6B035BF",
	"EC2107E58825A1586ACEE8E0911CE18260394AC8B87E535CA325F1CCBEB06BC6",
	"64E9A5F76F7A1E8B5A47D6A1F9A26522A251208F5276BDFA1559DAC7CF2E827A"
};
const string nativeHash = "F6E14157525F8AA69F6BD1564EC306717BCD6992B54280B92A105904F1868B82";
var verify = args.Length > 0 && args[0] == "--verify";
var paths = verify ? args[1..] : args;
if ( paths.Length != 4 ) {
	Console.Error.WriteLine( "Usage: GeneratePcreUnicodeScripts [--verify] Scripts.txt ScriptExtensions.txt PropertyValueAliases.txt PcreUnicodeScripts.Data.cs" );
	return 2;
}
var sources = new string[3];
for ( var i = 0; i < sources.Length; i++ ) {
	var bytes = File.ReadAllBytes( paths[i] );
	if ( Convert.ToHexString( SHA256.HashData( bytes ) ) != hashes[i] ) {
		Console.Error.WriteLine( "Expected the pinned Unicode17 source SHA256: " + paths[i] );
		return 1;
	}
	sources[i] = Encoding.UTF8.GetString( bytes );
}
var scripts = sources[2].Split( '\n' ).Select( line => line.Split( '#' )[0].Split( ';' ).Select( field => field.Trim() ).ToArray() )
	.Where( fields => fields.Length >= 3 && fields[0] == "sc" && fields[1] != "Hrkt" )
	.OrderBy( fields => fields[1], StringComparer.Ordinal ).ToArray();
if ( scripts.Length != 175 ) { throw new InvalidDataException( "Unexpected native script count." ); }
var shortIds = scripts.Select( (fields, id) => (fields[1], id) ).ToDictionary( item => item.Item1, item => item.id, StringComparer.Ordinal );
var longIds = scripts.Select( (fields, id) => (fields[2], id) ).ToDictionary( item => item.Item1, item => item.id, StringComparer.Ordinal );
var aliases = new SortedDictionary<string, byte>( StringComparer.Ordinal );
for ( var id = 0; id < scripts.Length; id++ ) {
	foreach ( var alias in scripts[id].Skip( 1 ).Where( value => value.Length > 0 ) ) {
		var name = Normalize( alias );
		if ( aliases.TryGetValue( name, out var previous ) && previous != id ) { throw new InvalidDataException( "Colliding script aliases." ); }
		aliases[name] = (byte)id;
	}
}
var primary = new byte[0x110000];
Array.Fill( primary, (byte)shortIds["Zzzz"] );
var assigned = new bool[primary.Length];
foreach ( var range in ReadRanges( sources[0] ) ) {
	var id = longIds[range.Value];
	for ( var scalar = range.Start; scalar <= range.End; scalar++ ) {
		if ( assigned[scalar] ) { throw new InvalidDataException( "Overlapping primary scripts." ); }
		assigned[scalar] = true;
		primary[scalar] = (byte)id;
	}
}
var basic = Enumerable.Range( 0, scripts.Length ).Select( _ => new List<(int Start, int End)>() ).ToArray();
var start = 0;
for ( var scalar = 1; scalar <= primary.Length; scalar++ ) {
	if ( scalar < primary.Length && primary[scalar] == primary[start] ) { continue; }
	basic[primary[start]].Add( (start, scalar - 1) );
	start = scalar;
}
var extended = basic.Select( ranges => new List<(int Start, int End)>( ranges ) ).ToArray();
var recordWidth = 1 + ( scripts.Length + 7 ) / 8;
var fingerprint = new byte[( 0x110000 - 0x800 ) * recordWidth];
for ( var scalar = 0; scalar < primary.Length; scalar++ ) {
	if ( scalar is >= 0xD800 and <= 0xDFFF ) { continue; }
	var at = ( scalar - ( scalar > 0xDFFF ? 0x800 : 0 ) ) * recordWidth;
	var id = primary[scalar];
	fingerprint[at] = id;
	fingerprint[at + 1 + ( id >> 3 )] |= (byte)( 1 << ( id & 7 ) );
}
var extensionAssigned = new bool[primary.Length];
foreach ( var range in ReadRanges( sources[1] ) ) {
	var ids = range.Value.Split( ' ', StringSplitOptions.RemoveEmptyEntries ).Select( code => shortIds[code] ).ToArray();
	foreach ( var id in ids ) { extended[id].Add( (range.Start, range.End) ); }
	for ( var scalar = range.Start; scalar <= range.End; scalar++ ) {
		if ( extensionAssigned[scalar] ) { throw new InvalidDataException( "Overlapping script extensions." ); }
		extensionAssigned[scalar] = true;
		if ( scalar is >= 0xD800 and <= 0xDFFF ) { continue; }
		var at = ( scalar - ( scalar > 0xDFFF ? 0x800 : 0 ) ) * recordWidth;
		foreach ( var id in ids ) { fingerprint[at + 1 + ( id >> 3 )] |= (byte)( 1 << ( id & 7 ) ); }
	}
}
if ( Convert.ToHexString( SHA256.HashData( fingerprint ) ) != nativeHash ) {
	throw new InvalidDataException( "Unicode source membership differs from the pinned native fingerprint." );
}
for ( var id = 0; id < extended.Length; id++ ) { extended[id] = Merge( extended[id] ); }
var output = new StringBuilder();
void Line( string value = "" ) => output.Append( value ).Append( '\n' );
Line( "// <auto-generated />" );
Line( "// Unicode 17.0.0 Scripts/ScriptExtensions/PropertyValueAliases; tools/GeneratePcreUnicodeScripts." );
foreach ( var hash in hashes ) { Line( "// Source SHA256: " + hash ); }
Line( "// Native scalar membership SHA256: " + nativeHash );
Line( "// Copyright © 2025 Unicode, Inc. See THIRD-PARTY-NOTICES.txt (Unicode License V3)." );
Line();
Line( "namespace Icod.Expressions.Pcre;" );
Line();
Line( "internal static partial class PcreUnicodeScripts {" );
Line( "\tinternal const int ScriptCount = 175;" );
Line( "\tprivate static readonly string[] NormalizedNames = {" );
var names = aliases.Keys.Select( name => "\"" + name + "\"" ).ToArray();
for ( var first = 0; first < names.Length; first += 4 ) { Line( "\t\t" + string.Join( ", ", names.Skip( first ).Take( 4 ) ) + "," ); }
Line( "\t};" );
Line( "\tprivate static ReadOnlySpan<byte> NameScripts => [" );
var values = aliases.Values.Select( value => value.ToString( CultureInfo.InvariantCulture ) ).ToArray();
for ( var first = 0; first < values.Length; first += 16 ) { Line( "\t\t" + string.Join( ", ", values.Skip( first ).Take( 16 ) ) + "," ); }
Line( "\t];" );
void EmitRanges( string prefix, List<(int Start, int End)>[] lists ) {
	var offsets = new List<string> { "0" };
	var entries = new List<string>();
	foreach ( var ranges in lists ) {
		foreach ( var range in ranges ) {
			entries.Add( "0x" + ( ( (ulong)range.Start << 21 ) | (uint)range.End ).ToString( "X16", CultureInfo.InvariantCulture ) + "UL" );
		}
		offsets.Add( checked((ushort)entries.Count).ToString( CultureInfo.InvariantCulture ) );
	}
	Line();
	Line( "\tprivate static ReadOnlySpan<ushort> " + prefix + "Offsets => [" );
	for ( var first = 0; first < offsets.Count; first += 12 ) { Line( "\t\t" + string.Join( ", ", offsets.Skip( first ).Take( 12 ) ) + "," ); }
	Line( "\t];" );
	Line( "\tprivate static ReadOnlySpan<ulong> " + prefix + "Ranges => [" );
	for ( var first = 0; first < entries.Count; first += 4 ) { Line( "\t\t" + string.Join( ", ", entries.Skip( first ).Take( 4 ) ) + "," ); }
	Line( "\t];" );
}
EmitRanges( "Primary", basic );
EmitRanges( "Extended", extended );
Line( "}" );
var generated = new UTF8Encoding( false ).GetBytes( output.ToString() );
if ( verify ) {
	if ( !File.ReadAllBytes( paths[3] ).AsSpan().SequenceEqual( generated ) ) {
		Console.Error.WriteLine( "Generated Unicode scripts differ from committed data." );
		return 1;
	}
	Console.WriteLine( $"Verified Unicode17 scripts: {scripts.Length} scripts, {aliases.Count} aliases, native fingerprint {nativeHash}." );
	return 0;
}
File.WriteAllBytes( paths[3], generated );
return 0;

static string Normalize( string value ) => new( value.Where( c => c is not ( '_' or '-' or ' ' ) )
	.Select( c => c is >= 'a' and <= 'z' ? (char)( c - 32 ) : c ).ToArray() );

static IEnumerable<(int Start, int End, string Value)> ReadRanges( string source ) {
	foreach ( var line in source.Split( '\n' ) ) {
		var text = line.Split( '#' )[0].Trim();
		if ( text.Length == 0 ) { continue; }
		var fields = text.Split( ';' );
		var limits = fields[0].Trim().Split( "..", StringSplitOptions.None );
		var first = int.Parse( limits[0], NumberStyles.HexNumber, CultureInfo.InvariantCulture );
		var last = int.Parse( limits[^1], NumberStyles.HexNumber, CultureInfo.InvariantCulture );
		if ( first < 0 || first > last || last > 0x10FFFF ) { throw new InvalidDataException( "Invalid script range." ); }
		yield return (first, last, fields[1].Trim());
	}
}

static List<(int Start, int End)> Merge( List<(int Start, int End)> ranges ) {
	ranges.Sort( static (left, right) => left.Start.CompareTo( right.Start ) );
	var result = new List<(int Start, int End)>();
	foreach ( var range in ranges ) {
		if ( result.Count > 0 && range.Start <= result[^1].End + 1 ) {
			result[^1] = (result[^1].Start, Math.Max( result[^1].End, range.End ));
		} else { result.Add( range ); }
	}
	return result;
}
