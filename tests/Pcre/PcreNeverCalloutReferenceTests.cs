	[Fact]
	public void CallerGuardRetainsCanonicalWorkAndCancellation() {
		var source = Encoding.ASCII.GetBytes( @"(*MARK:(?C)A(A|AA)+B" );
		var subject = "AAAAB"u8.ToArray();
		var reference = Reference( source, true, 1 );
		AssertLiteral( reference, subject, 0, "0:5,3:1", "283F43" );
		var guarded = new List<int>();
		var ordinary = new List<int>();
		var options = Options( true, 1 ) with { WorkObserver = guarded.Add };
		Compare( reference, subject, 0, Compile( source, options ).Match( subject ), "guarded work" );
		Compare( reference, subject, 0, Compile( source, Options( false, 1 ) with { WorkObserver = ordinary.Add } ).Match( subject ), "ordinary work" );
		Assert.Equal( ordinary, guarded );
		Assert.Equal( Enumerable.Range( 1, guarded.Count ), guarded );
		Assert.True( guarded.Count > 2 );
		var limited = Compile( source, options with { MatchWorkLimit = guarded.Count - 1 } ).Match( subject );
		Assert.Equal( PcreByteDiagnosticCode.MatchWorkLimitExceeded, limited.Diagnostic?.Code );
		Assert.Null( limited.Match );
		using var cancellation = new CancellationTokenSource();
		var compiled = Compile( source, options with { WorkObserver = count => { if ( count == 2 ) { cancellation.Cancel(); } } } );
		Assert.Throws<OperationCanceledException>( () => compiled.Match( subject, 0, cancellation.Token ) );
		Assert.Throws<OperationCanceledException>( () => PcreByteCompiler.Compile( "(?C1)"u8.ToArray(), options, cancellation.Token ) );
		var invalidWork = PcreByteCompiler.Compile( "(?C1)"u8.ToArray(), options with { MatchWorkLimit = 0 } );
		Assert.Equal( PcreByteDiagnosticCode.InvalidWorkLimit, invalidWork.Diagnostic?.Code );
	}

	[Fact]
	public void InertCompiledPatternsOwnTheirSourceOptionsAndLabelData() {
		var source = Encoding.ASCII.GetBytes( @"\Q(?C1)\E(*MARK:(?C)(A)\1" );
		var subject = "(?C1)AA"u8.ToArray();
