	[Theory]
	[InlineData( "\\é(A)", "\\x{E9}(A)", "C3A941", 7, "0:3,2:1", "" )]
	[InlineData( "[\\é-\\ê]+A", "[\\x{E9}-\\x{EA}]+A", "C3A9C3AA41", 7, "0:5", "" )]
	[InlineData( "(?<=\\é)A", "(?<=\\x{E9})A", "C3A941", 7, "2:1", "" )]
	[InlineData( "(?i)(\\K)\\1", "(?i)(\\x{212A})\\1", "4BE284AA", 7, "0:4,0:1", "" )]
	[InlineData( "(*MARK:\\é)\\é(A)", "(*MARK:\\é)\\x{E9}(A)", "C3A941", 135, "0:3,2:1", "C3A9" )]
	public void CanonicalLiteralSharesWorkCancellationAndOwnedState( string pattern, string canonical, string hex, int mode, string spans, string mark ) {
		var source = Encoding.UTF8.GetBytes( pattern );
		var canonicalSource = Encoding.UTF8.GetBytes( canonical );
		var subject = Convert.FromHexString( hex );
		var reference = Reference( source, mode );
		var canonicalReference = Reference( canonicalSource, mode );
		AssertLiteral( reference, subject, 0, spans, mark );
		AssertLiteral( canonicalReference, subject, 0, spans, mark );
		var actualSteps = new List<int>();
		var canonicalSteps = new List<int>();
		var options = Options( mode ) with { WorkObserver = actualSteps.Add };
		var compiled = Compile( source, options );
		Array.Fill( source, (byte)'x' );
		typeof( PcreByteOptions ).GetProperty( "Utf8" )!.SetValue( options, false );
		typeof( PcreByteOptions ).GetProperty( "MatchInvalidUtf" )!.SetValue( options, false );
		typeof( PcreByteOptions ).GetProperty( "AltVerbNames" )!.SetValue( options, false );
		Compare( reference, subject, 0, compiled.Match( subject ), "owned escaped scalar" );
		Compare( canonicalReference, subject, 0, Compile( canonicalSource, Options( mode ) with { WorkObserver = canonicalSteps.Add } ).Match( subject ), "canonical work" );
		Assert.Equal( canonicalSteps, actualSteps );
		Assert.Equal( Enumerable.Range( 1, actualSteps.Count ), actualSteps );
		Assert.True( actualSteps.Count > 2 );
		var limited = Compile( Encoding.UTF8.GetBytes( pattern ), Options( mode ) with { MatchWorkLimit = actualSteps.Count - 1 } ).Match( subject );
		Assert.Equal( PcreByteDiagnosticCode.MatchWorkLimitExceeded, limited.Diagnostic?.Code );
		Assert.Null( limited.Match );
		using var cancellation = new CancellationTokenSource();
		var cancellable = Compile( Encoding.UTF8.GetBytes( pattern ), Options( mode ) with {
			WorkObserver = count => { if ( count == 2 ) { cancellation.Cancel(); } }
		} );
		Assert.Throws<OperationCanceledException>( () => cancellable.Match( subject, 0, cancellation.Token ) );
		Assert.Throws<OperationCanceledException>( () => PcreByteCompiler.Compile( source, options, cancellation.Token ) );
		var invalid = PcreByteCompiler.Compile( "("u8.ToArray(), Options( mode ) with { MatchWorkLimit = 0 } );
		Assert.Equal( PcreByteDiagnosticCode.InvalidWorkLimit, invalid.Diagnostic?.Code );
	}

