	public void EveryPredicateByteRespectsNativeUcpAndLocalAsciiPolicy( string body, string normal, string insensitive ) {
		foreach ( var caseless in new[] { false, true } ) {
			var mask = Convert.FromHexString( caseless ? insensitive : normal );
			var source = String.Concat( caseless ? "(?i)" : "", @"\A", body, @"\z" );
			var prefix = Compile( "(*UCP)" + source );
			var caller = Compile( source, new() { Ucp = true } );
			var reference = Reference( "(*UCP)" + source );
			for ( var value = 0; value < 256; value++ ) {
				var subject = new[] { (byte)value };
				var want = Member( mask, value );
				Assert.Equal( want, reference.Match( subject ).Success );
				AssertMatch( prefix.Match( subject ), want, 1 );
				AssertMatch( caller.Match( subject ), want, 1 );
			}
		}
	}

