	[Theory]
	[InlineData( 1, "A$(*MARK:# [])", "41", "410A", "0:1" )]
	[InlineData( 2, @"(?m)\n^(*MARK:# [])", "0A", "0A", "0:1" )]
	[InlineData( 3, @"(?m)\n^$(*MARK:# [])", "0A", "0A", "0:1" )]
	public void CompiledAnchorStateOwnsFlagsSourceAndRawLabels( int selection, string pattern, string hex, string alternateHex, string spans ) {
		var source = Encoding.ASCII.GetBytes( pattern );
		var options = Options( selection, 3 );
		var subject = Convert.FromHexString( hex );
		var reference = Reference( pattern, selection, options );
		AssertLiteral( reference, subject, spans );
		var result = PcreByteCompiler.Compile( source, options );
		Assert.True( result.IsSuccess );
		Array.Fill( source, (byte)'x' );
		SetSelection( options, 0 );
		Compare( reference, subject, 0, result.Pattern!.Match( subject ), "owned anchor state" );
		Assert.Equal( "# []", Encoding.ASCII.GetString( result.Pattern.Match( subject ).Match!.MarkName.Span ) );
		var alternate = Convert.FromHexString( alternateHex );
		if ( selection == 1 ) {
			Assert.Null( result.Pattern.Match( alternate ).Match );
			Assert.NotNull( Compile( pattern, Options( 0, 3 ) ).Match( alternate ).Match );
		} else {
			Assert.NotNull( result.Pattern.Match( alternate ).Match );
			Assert.Null( Compile( pattern, Options( 0, 3 ) ).Match( alternate ).Match );
		}
	}

	[Theory]
	[InlineData( 1 )]
	[InlineData( 2 )]
	[InlineData( 3 )]
	public void AnchorFlagsRetainCanonicalWorkCancellationAndExistingLimits( int selection ) {
		var pattern = ( selection & 1 ) != 0 ? "(?<x>A+)$" : "(?m)^(?<x>A+)$";
		var canonical = ( selection & 1 ) != 0 ? @"(?<x>A+)\z" : pattern;
		var subject = Enumerable.Repeat( (byte)'A', 1024 ).ToArray();
		var options = Options( selection, 3 );
		var steps = new List<int>();
		var canonicalSteps = new List<int>();
		var reference = Reference( pattern, selection, options );
		AssertLiteral( reference, subject, "0:1024,0:1024" );
		Compare( reference, subject, 0, Compile( pattern, options with { WorkObserver = steps.Add } ).Match( subject ), "anchor work" );
		Assert.NotNull( Compile( canonical, Options( 0, 3 ) with { WorkObserver = canonicalSteps.Add } ).Match( subject ).Match );
		Assert.Equal( canonicalSteps, steps );
		Assert.Equal( Enumerable.Range( 1, steps.Count ), steps );
		var limited = Compile( pattern, options with { MatchWorkLimit = steps.Count - 1 } ).Match( subject );
		Assert.Null( limited.Match );
		Assert.Equal( PcreByteDiagnosticCode.MatchWorkLimitExceeded, limited.Diagnostic?.Code );
		using var cancellation = new CancellationTokenSource();
		var cancellable = Compile( pattern, options with { WorkObserver = count => { if ( count == 4 ) { cancellation.Cancel(); } } } );
		Assert.Throws<OperationCanceledException>( () => cancellable.Match( subject, cancellationToken: cancellation.Token ) );
		Assert.Throws<OperationCanceledException>( () => PcreByteCompiler.Compile( Encoding.ASCII.GetBytes( pattern ), options, cancellation.Token ) );
		Assert.Equal( PcreByteDiagnosticCode.PatternCaptureLimitExceeded, PcreByteCompiler.Compile( Encoding.ASCII.GetBytes( String.Concat( Enumerable.Repeat( "()", 257 ) ) ), options ).Diagnostic?.Code );
		Assert.Equal( PcreByteDiagnosticCode.PatternRepeatLimitExceeded, PcreByteCompiler.Compile( "A{4096}"u8.ToArray(), options ).Diagnostic?.Code );
		var deep = String.Concat( new string( '(', 257 ), new string( ')', 257 ) );
		Assert.Equal( PcreByteDiagnosticCode.PatternDepthLimitExceeded, PcreByteCompiler.Compile( Encoding.ASCII.GetBytes( deep ), options ).Diagnostic?.Code );
	}

	private static PcreByteOptions Options( int selection, int mode ) {
		var options = new PcreByteOptions { Utf8 = ( mode & 1 ) != 0, Ucp = ( mode & 2 ) != 0, Multiline = ( mode & 4 ) != 0, MatchLine = ( mode & 8 ) != 0, MatchWord = ( mode & 16 ) != 0 };
		SetSelection( options, selection );
		return options;
	}
	private static void SetSelection( PcreByteOptions options, int selection ) {
		typeof( PcreByteOptions ).GetProperty( "DollarEndOnly" )?.SetValue( options, ( selection & 1 ) != 0 );
		typeof( PcreByteOptions ).GetProperty( "AltCircumflex" )?.SetValue( options, ( selection & 2 ) != 0 );
	}
	private static ReadOnlyMemory<byte> Mark( PcreByteMatch match ) => match.MarkName;
	private static void AssertLiteral( PcreRegex8Bit reference, byte[] subject, string spans ) {
		var match = reference.Match( subject );
		Assert.Equal( spans.Length > 0, match.Success );
		if ( !match.Success ) { return; }
		var groups = spans.Split( ',' );
		Assert.Equal( groups.Length, match.Groups.Count );
		for ( var group = 0; group < groups.Length; group++ ) {
			var capture = match.Groups[group];
			Assert.Equal( groups[group], capture.Success ? $"{capture.Index}:{capture.Length}" : "-" );
		}
	}

	private static void Compare( PcreRegex8Bit reference, byte[] subject, int offset, PcreByteMatchResult actual, string context ) {
		var expected = reference.Match( subject, offset );
		Assert.True( actual.IsSuccess, $"{context}: {actual.Diagnostic?.Message}" );
		Assert.True( ( expected.Success ? expected.Index : -1 ) == ( actual.Match?.ByteIndex ?? -1 ), context );
		if ( !expected.Success ) { return; }
		Assert.Equal( expected.Mark.ToArray(), Mark( actual.Match! ).ToArray() );
		Assert.Equal( expected.Length, actual.Match!.ByteLength );
		Assert.Equal( expected.Groups.Count, actual.Match.Captures.Count );
		for ( var group = 0; group < expected.Groups.Count; group++ ) {
			var capture = expected.Groups[group];
			Assert.Equal( capture.Success ? new PcreByteCapture( capture.Index, capture.Length ) : null, actual.Match.Captures[group] );
		}
	}

	private static PcreRegex8Bit Reference( string pattern, int selection, PcreByteOptions options ) => Reference( Encoding.UTF8.GetBytes( pattern ), selection, options );
	private static PcreRegex8Bit Reference( byte[] pattern, int selection, PcreByteOptions options ) => new( pattern, Encoding.UTF8, new PcreRegexSettings {
		Options = PcreOptions.Compiled | (PcreOptions)( ( selection & 1 ) != 0 ? 0x10 : 0 ) | (PcreOptions)( ( selection & 2 ) != 0 ? 0x200000 : 0 ) | ( options.Caseless ? PcreOptions.Caseless : PcreOptions.None ) | ( options.Multiline ? (PcreOptions)0x400 : PcreOptions.None ) | ( options.DotAll ? (PcreOptions)0x20 : PcreOptions.None ) | ( options.NoAutoCapture ? (PcreOptions)0x2000 : PcreOptions.None ) | ( options.Ungreedy ? (PcreOptions)0x40000 : PcreOptions.None ) | ( options.DuplicateNames ? (PcreOptions)0x40 : PcreOptions.None ) | ( options.Extended ? (PcreOptions)0x80 : PcreOptions.None ) | ( options.ExtendedMore ? (PcreOptions)0x01000000 : PcreOptions.None ) | ( options.Utf8 || options.MatchInvalidUtf ? PcreOptions.Utf : PcreOptions.None ) | ( options.Ucp ? PcreOptions.Ucp : PcreOptions.None ) | ( options.MatchInvalidUtf ? PcreOptions.MatchInvalidUtf : PcreOptions.None ) | ( options.AltExtendedClass ? (PcreOptions)0x08000000 : PcreOptions.None ) | ( options.AllowEmptyClass ? (PcreOptions)0x1 : PcreOptions.None ),
		ExtraCompileOptions = (PcreExtraCompileOptions)( options.MatchWord ? 4 : 0 ) | (PcreExtraCompileOptions)( options.MatchLine ? 8 : 0 ) | (PcreExtraCompileOptions)( options.PythonOctal ? 0x2000 : 0 ) | (PcreExtraCompileOptions)( options.NoBackslashZero ? 0x4000 : 0 ) | (PcreExtraCompileOptions)( options.EscapedCrIsLf ? 0x10 : 0 ) | (PcreExtraCompileOptions)( options.AsciiBsD ? 0x100 : 0 ) | (PcreExtraCompileOptions)( options.AsciiBsS ? 0x200 : 0 ) | (PcreExtraCompileOptions)( options.AsciiBsW ? 0x400 : 0 ) | (PcreExtraCompileOptions)( options.AsciiPosix ? 0x800 : 0 ) | (PcreExtraCompileOptions)( options.AsciiDigit ? 0x1000 : 0 ),
		NewLine = options.AnyCrLfNewline ? PcreNewLine.AnyCrLf : PcreNewLine.Lf, ParensLimit = 512
	} );

	private static PcreCompiledBytePattern Compile( string pattern, PcreByteOptions options ) {
		var result = PcreByteCompiler.Compile( Encoding.UTF8.GetBytes( pattern ), options );
		Assert.True( result.IsSuccess, $"{pattern}: {result.Diagnostic?.Message}" );
		return Assert.IsType<PcreCompiledBytePattern>( result.Pattern );
	}
