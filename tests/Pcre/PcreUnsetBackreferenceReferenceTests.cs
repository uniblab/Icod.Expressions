	[Fact]
	public void UnsetAndParticipatingPathsShareWorkCancellationAndLimits() {
		const string pattern = @"(A)?\1B+";
		const string participating = @"(A+)\1";
		var subject = Enumerable.Repeat( (byte)'B', 1024 ).ToArray();
		var peerSubject = Enumerable.Repeat( (byte)'A', 32 ).ToArray();
		var options = Options( true, 3 );
		var reference = Reference( pattern, true, options );
		var peerReference = Reference( participating, true, options );
		AssertLiteral( reference, subject, "0:1024,-" );
		AssertLiteral( peerReference, peerSubject, "0:32,0:16" );
		var steps = new List<int>();
		Compare( reference, subject, 0, Compile( pattern, options with { WorkObserver = steps.Add } ).Match( subject ), "unset work" );
		Assert.Equal( Enumerable.Range( 1, steps.Count ), steps );
		var enabledSteps = new List<int>();
		var defaultSteps = new List<int>();
		Assert.NotNull( Compile( participating, options with { WorkObserver = enabledSteps.Add } ).Match( peerSubject ).Match );
		Assert.NotNull( Compile( participating, Options( false, 3 ) with { WorkObserver = defaultSteps.Add } ).Match( peerSubject ).Match );
		Assert.Equal( defaultSteps, enabledSteps );
		var limited = Compile( pattern, options with { MatchWorkLimit = steps.Count - 1 } ).Match( subject );
		Assert.Null( limited.Match );
		Assert.Equal( PcreByteDiagnosticCode.MatchWorkLimitExceeded, limited.Diagnostic?.Code );
		using var cancellation = new CancellationTokenSource();
		var cancellable = Compile( pattern, options with { WorkObserver = count => { if ( count == 4 ) { cancellation.Cancel(); } } } );
		Assert.Throws<OperationCanceledException>( () => cancellable.Match( subject, cancellationToken: cancellation.Token ) );
		Assert.Throws<OperationCanceledException>( () => PcreByteCompiler.Compile( Encoding.ASCII.GetBytes( pattern ), options, cancellation.Token ) );
		Assert.Equal( PcreByteDiagnosticCode.PatternCaptureLimitExceeded, PcreByteCompiler.Compile( Encoding.ASCII.GetBytes( String.Concat( Enumerable.Repeat( "()", 257 ) ) ), options ).Diagnostic?.Code );
		Assert.Equal( PcreByteDiagnosticCode.PatternRepeatLimitExceeded, PcreByteCompiler.Compile( "A{4096}"u8.ToArray(), options ).Diagnostic?.Code );
		var deep = String.Concat( new string( '(', 257 ), new string( ')', 257 ) );
		Assert.Equal( PcreByteDiagnosticCode.PatternDepthLimitExceeded, PcreByteCompiler.Compile( Encoding.ASCII.GetBytes( deep ), options ).Diagnostic?.Code );
	}

